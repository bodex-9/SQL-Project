CREATE FUNCTION USERINFO(@PHONE VARCHAR(20))
RETURNS TABLE
AS
RETURN
(
SELECT BK.TITLE,UL.NAME,B.AMOUNT_OF_MONEY,B.DUE_DATE
FROM USER_PHONE UP JOIN USERLIBARAY UL
ON UP.USER_SSN = UL.SSN
JOIN BORROW B
ON UP.USER_SSN = B.USER_SSN
JOIN BOOK BK
ON BK.BOOK_ID = B.BOOK_ID
WHERE UP.PHONE = @PHONE
)
GO
