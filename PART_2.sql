CREATE FUNCTION CKECKDUPLICATE
(
    @USERNAME NVARCHAR(30)
)
RETURNS NVARCHAR(100)
AS
BEGIN
    DECLARE @COUNT INT
    DECLARE @MESSAGE NVARCHAR(100)

    SELECT @COUNT = COUNT(*)
    FROM USERLIBARAY
    WHERE NAME = @USERNAME

    IF (@COUNT = 0)
    BEGIN
        SET @MESSAGE = @USERNAME + ' IS NOT FOUND'
    END
    ELSE IF (@COUNT = 1)
    BEGIN
        SET @MESSAGE = @USERNAME + ' IS NOT DUPLICATED'
    END
    ELSE
    BEGIN
        SET @MESSAGE = @USERNAME + ' IS REPEATED '
                     + CAST(@COUNT AS VARCHAR(10))
                     + ' TIMES'
    END

    RETURN @MESSAGE
END
GO

SELECT dbo.CKECKDUPLICATE('Yasmin Adel')
